-- Scenes played against the headless worlds (tests/world/): crafting through the game
-- and through Daylight UI's window, and the checklist following the player.

local CP = ProfLost
local LW, KIT, LIGHT_LEATHER, KIT_ITEM = 165, 2152, 2318, 2304

T.test("the Craft button's batch counts down cast by cast, uses the materials and raises the skill", function()
    MapWorld.begin()
    CraftWorld.begin({ professions = { [LW] = 1 }, bags = { [LIGHT_LEATHER] = 10 } })
    CraftWorld.Open(LW)
    CP.Crafting.Start(KIT, 3)
    T.eq(CraftWorld.state.casts[1], { id = KIT, count = 3 }, "one CraftRecipe for the batch")
    T.ok(CP.Crafting.ShowStrip(), "our strip shows our batch")
    CraftWorld.Cast()
    T.eq({ CP.Crafting.Progress() }, { 1, 3 })
    CraftWorld.Cast()
    CraftWorld.Cast()
    T.ok(not CP.Crafting.Busy(), "done after the third")
    T.eq(CraftWorld.Bag(LIGHT_LEATHER), 7)
    T.eq(CraftWorld.Bag(KIT_ITEM), 3)
    T.eq(CP.Professions.Current().skill, 4, "three orange crafts, three points")
end)

T.test("a failed cast ends the batch", function()
    MapWorld.begin()
    CraftWorld.begin({ professions = { [LW] = 1 }, bags = { [LIGHT_LEATHER] = 10 } })
    CraftWorld.Open(LW)
    CP.Crafting.Start(KIT, 5)
    CraftWorld.Cast()
    CraftWorld.Cast(false)
    T.ok(not CP.Crafting.Busy())
    T.eq(CraftWorld.Bag(LIGHT_LEATHER), 9, "only the first cast used leather")
    T.eq(CraftWorld.Cast(), false, "nothing left to cast")
end)

T.test("Daylight UI's Create button drives the strip state; its window shows the progress", function()
    DaylightWorld.begin({ plugin = true })
    MapWorld.begin()
    CraftWorld.begin({ professions = { [LW] = 1 }, bags = { [LIGHT_LEATHER] = 10 } })
    CraftWorld.Open(LW)
    T.ok(CP.Host.DaylightWindow(), "Daylight UI's window is up")
    DaylightWorld.Create(KIT, 2)
    T.ok(CP.Crafting.Busy() and not CP.Crafting.ShowStrip(), "their batch: our buttons wait, no strip of ours")
    CraftWorld.Cast()
    T.eq({ CP.Crafting.Progress() }, { 1, 2 })
    CraftWorld.Cast()
    T.ok(not CP.Crafting.Busy(), "CraftStopped ends it")
    T.eq(CP.Crafting.daylight, nil)
end)

T.test("picking a learned step selects it in Daylight UI's window; their pick moves the guide", function()
    DaylightWorld.begin({ plugin = true })
    MapWorld.begin()
    CraftWorld.begin({ professions = { [LW] = 1 }, bags = { [LIGHT_LEATHER] = 10 } })
    CraftWorld.Open(LW)
    T.ok(CP.Professions.Open(KIT), "Daylight UI confirms the recipe shows")
    T.eq(DaylightWorld.state.selected, KIT)
    T.ok(not CP.Professions.Open(2153), "an unlearned recipe can't be picked there")
end)

T.test("the Gather tab follows the player into another zone", function()
    MapWorld.begin({ zone = 1411, level = 10, side = "Horde" })
    CraftWorld.begin({ professions = { [186] = 30 } })
    CP.GatherList.Refresh()
    T.eq(CP.GatherList.zone, 1411)
    MapWorld.Move(1413, 0.5, 0.5)
    T.advance(0.5)
    T.eq(CP.GatherList.zone, 1413, "The Barrens after the move")
end)
